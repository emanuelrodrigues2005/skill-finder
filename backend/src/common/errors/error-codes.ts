/**
 * Códigos de erro estáveis de `docs/app/02-arquitetura.md` §5.5.
 *
 * O frontend decide a mensagem pelo código, nunca pelo texto: renomear um código
 * é mudança de contrato.
 */
export const ERROR_CODES = {
  BAD_REQUEST: 'BAD_REQUEST',
  VALIDATION_ERROR: 'VALIDATION_ERROR',
  UNAUTHORIZED: 'UNAUTHORIZED',
  FORBIDDEN: 'FORBIDDEN',
  NOT_FOUND: 'NOT_FOUND',
  CONFLICT: 'CONFLICT',
  HISTORY_EXPIRED: 'HISTORY_EXPIRED',
  RATE_LIMITED: 'RATE_LIMITED',
  LLM_BAD_RESPONSE: 'LLM_BAD_RESPONSE',
  SOURCE_UNAVAILABLE: 'SOURCE_UNAVAILABLE',
  NOT_READY: 'NOT_READY',
  INTERNAL: 'INTERNAL',
} as const;

export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

const STATUS_TO_CODE: Record<number, ErrorCode> = {
  400: ERROR_CODES.BAD_REQUEST,
  401: ERROR_CODES.UNAUTHORIZED,
  403: ERROR_CODES.FORBIDDEN,
  404: ERROR_CODES.NOT_FOUND,
  405: ERROR_CODES.BAD_REQUEST,
  409: ERROR_CODES.CONFLICT,
  410: ERROR_CODES.HISTORY_EXPIRED,
  422: ERROR_CODES.VALIDATION_ERROR,
  429: ERROR_CODES.RATE_LIMITED,
  500: ERROR_CODES.INTERNAL,
  502: ERROR_CODES.LLM_BAD_RESPONSE,
  503: ERROR_CODES.SOURCE_UNAVAILABLE,
  504: ERROR_CODES.LLM_BAD_RESPONSE,
};

export function codeForStatus(status: number): ErrorCode {
  return STATUS_TO_CODE[status] ?? ERROR_CODES.INTERNAL;
}
